"""
SQL Query Cleaner

Cleans and normalizes SQL queries generated by LLMs to ensure they are valid.
Handles common issues like line continuation characters, extra whitespace, etc.
"""

import re
from typing import Tuple


def clean_sql_query(sql: str) -> str:
    """
    Clean and normalize a SQL query to ensure it's valid.

    Handles:
    - Line continuation characters (backslashes)
    - Duplicate SELECT statements
    - Extra whitespace
    - Unnecessary newlines

    Args:
        sql: Raw SQL query string

    Returns:
        Cleaned SQL query string
    """
    if not sql:
        return ""

    # Remove line continuation characters (backslashes)
    # Common issue with LLMs that format SQL with Python-style line continuations
    sql = re.sub(r'\\\s*\n', ' ', sql)
    sql = re.sub(r'\\\s*$', '', sql, flags=re.MULTILINE)

    # Remove any remaining standalone backslashes
    sql = sql.replace('\\', '')

    # Fix duplicate SELECT statements (another common LLM mistake)
    # Pattern: "SELECT ... SELECT ..." -> just one SELECT
    sql = re.sub(r'SELECT\s+([^,]+),\s*SELECT\s+', r'SELECT ', sql, flags=re.IGNORECASE)

    # Normalize whitespace
    # Replace multiple spaces with single space
    sql = re.sub(r'\s+', ' ', sql)

    # Remove leading/trailing whitespace
    sql = sql.strip()

    # Remove trailing semicolon if present (will be added back by executor if needed)
    sql = sql.rstrip(';').strip()

    return sql


def validate_and_clean_sql(sql: str) -> Tuple[str, str]:
    """
    Validate and clean a SQL query, returning both the cleaned query and any warnings.

    Args:
        sql: Raw SQL query string

    Returns:
        Tuple of (cleaned_sql, warning_message)
        warning_message will be empty string if no issues found
    """
    original_sql = sql
    warnings = []

    # Clean the SQL
    cleaned_sql = clean_sql_query(sql)

    # Check if we made significant changes
    if '\\' in original_sql:
        warnings.append("Removed line continuation characters from SQL")

    # Check for duplicate SELECT keywords
    select_count = len(re.findall(r'\bSELECT\b', original_sql, re.IGNORECASE))
    cleaned_select_count = len(re.findall(r'\bSELECT\b', cleaned_sql, re.IGNORECASE))

    if select_count > cleaned_select_count:
        warnings.append("Removed duplicate SELECT statements")

    # Check for common syntax issues
    if cleaned_sql:
        # Check for unmatched parentheses
        open_parens = cleaned_sql.count('(')
        close_parens = cleaned_sql.count(')')
        if open_parens != close_parens:
            warnings.append(f"Warning: Unmatched parentheses (found {open_parens} opening, {close_parens} closing)")

    warning_message = "; ".join(warnings) if warnings else ""

    return cleaned_sql, warning_message
